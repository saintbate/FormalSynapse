// One-hot handshake FSM: IDLE -> REQ -> ACK -> DONE -> IDLE.
module onehot_fsm (
    input  logic clk,
    input  logic rst_n,
    input  logic start,
    input  logic ack_in,
    output logic req,
    output logic done,
    output logic [3:0] state
);
    localparam logic [3:0] S_IDLE = 4'b0001;
    localparam logic [3:0] S_REQ  = 4'b0010;
    localparam logic [3:0] S_ACK  = 4'b0100;
    localparam logic [3:0] S_DONE = 4'b1000;

    /* verilator lint_off MULTIDRIVEN */
    initial state = S_IDLE;
    always_ff @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            state <= S_IDLE;
        end else begin
            unique case (state)
                S_IDLE: state <= start  ? S_REQ  : S_IDLE;
                S_REQ:  state <= ack_in ? S_ACK  : S_REQ;
                S_ACK:  state <= S_DONE;
                S_DONE: state <= S_IDLE;
                default: state <= S_IDLE;
            endcase
        end
    end
    /* verilator lint_on MULTIDRIVEN */

    assign req  = (state == S_REQ);
    assign done = (state == S_DONE);

