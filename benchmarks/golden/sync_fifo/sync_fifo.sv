// Synchronous FIFO, depth 4, 8-bit data. Writes while full and reads while empty are ignored.
module sync_fifo (
    input  logic       clk,
    input  logic       rst_n,
    input  logic       wr_en,
    input  logic       rd_en,
    input  logic [7:0] wr_data,
    output logic [7:0] rd_data,
    output logic       full,
    output logic       empty,
