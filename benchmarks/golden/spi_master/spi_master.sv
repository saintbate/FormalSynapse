// Minimal SPI master: 8-bit MSB-first, sclk = clk/2, one-cycle `done` pulse.
module spi_master (
    input  logic       clk,
    input  logic       rst_n,
    input  logic       start,
    input  logic [7:0] data_in,
    output logic       sclk,
    output logic       mosi,
    output logic       cs_n,
    output logic       busy,
    output logic       done
);
    logic [7:0] shifter;
    logic [3:0] bit_cnt;
    logic       phase;
    /* verilator lint_off MULTIDRIVEN */
    initial shifter = 8'd0;
    initial bit_cnt = 4'd0;
    initial phase   = 1'b0;
    initial busy    = 1'b0;
    initial done    = 1'b0;

    assign mosi = shifter[7];
    assign sclk = busy && phase;
    assign cs_n = !busy;

    always_ff @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            shifter <= 8'd0;
            bit_cnt <= 4'd0;
            phase   <= 1'b0;
            busy    <= 1'b0;
            done    <= 1'b0;
        end else begin
            done <= 1'b0;
            if (!busy) begin
                phase <= 1'b0;
                if (start) begin
                    shifter <= data_in;
                    bit_cnt <= 4'd0;
                    busy    <= 1'b1;
                end
            end else if (!phase) begin
                phase <= 1'b1;
            end else begin
                phase   <= 1'b0;
                shifter <= {shifter[6:0], 1'b0};
                if (bit_cnt == 4'd7) begin
                    busy <= 1'b0;
                    done <= 1'b1;
                end else begin
                    bit_cnt <= bit_cnt + 4'd1;
                end
            end
        end
    end
    /* verilator lint_on MULTIDRIVEN */

